from pathlib import Path
from datetime import datetime
import time

import polars as pl

from finomaly.config import (
    RANDOM_STATE,
    MODEL_ESTIMATORS,
)


PROJECT_ROOT = Path(__file__).resolve().parents[2]
EXPERIMENT_DIR = PROJECT_ROOT / "logs" / "experiments"


def save_experiment_report(
    results: pl.DataFrame,
    metrics: dict,
    model,
    experiment_name: str,
    algorithm: str,
    features: list[str],
    execution_time: float,
    notes: str = "",
):
    """
    Save an experiment's configuration and results
    as a Markdown report.
    """

    EXPERIMENT_DIR.mkdir(parents=True, exist_ok=True)

    total = results.height

    fraud_count = results.filter(
        pl.col("isFraud") == 1
    ).height

    legitimate_count = total - fraud_count

    params = model.get_params()

    # Confusion matrix values
    tp = metrics["true_positives"]
    fp = metrics["false_positives"]
    fn = metrics["false_negatives"]
    tn = legitimate_count - fp

    report = f"""# {experiment_name}

## 1. Experiment Information

- Algorithm: {algorithm}
- Date: {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}
- Dataset: PaySim
- Random state: {RANDOM_STATE}
- Execution time: {execution_time:.2f} seconds

## 2. Model Configuration

| Parameter | Value |
|---|---|
| Estimators | {params.get("n_estimators", "N/A")} |
| Contamination | {params.get("contamination", "N/A")} |
| Random state | {params.get("random_state", "N/A")} |
| Number of jobs | {params.get("n_jobs", "N/A")} |

## 3. Features Used

{chr(10).join(f"- {feature}" for feature in features)}

Fraud labels were excluded from model training.

## 4. Dataset Summary

| Metric | Value |
|---|---:|
| Transactions evaluated | {total:,} |
| Legitimate transactions | {legitimate_count:,} |
| Fraudulent transactions | {fraud_count:,} |
| Fraud percentage | {(fraud_count / total * 100 if total else 0):.4f}% |

## 5. Model Performance

| Metric | Result |
|---|---:|
| Anomalies detected | {metrics["anomalies_detected"]:,} |
| True positives | {tp:,} |
| False positives | {fp:,} |
| False negatives | {fn:,} |
| Precision | {metrics["precision"]:.4f} |
| Recall | {metrics["recall"]:.4f} |
| F1-score | {metrics["f1_score"]:.4f} |

## 6. Confusion Matrix

| | Predicted Fraud/Anomaly | Predicted Normal |
|---|---:|---:|
| Actual Fraud | {tp:,} | {fn:,} |
| Actual Legitimate | {fp:,} | {tn:,} |

Note: Anomaly predictions are compared with the dataset's fraud labels
after model training. An anomaly is not necessarily fraud.

## 7. Top 10 Anomalies

| Step | Type | Amount | Actual Fraud | Anomaly Score |
|---:|---|---:|---:|---:|
"""

    top_results = results.head(10)

    for row in top_results.iter_rows(named=True):
        report += (
            f'| {row["step"]} '
            f'| {row["type"]} '
            f'| {row["amount"]:.2f} '
            f'| {row["isFraud"]} '
            f'| {row["anomaly_score"]:.6f} |\\n'
        )

    report += f"""

## 8. Observations

{notes}

## 9. Reproducibility

- Random state: {RANDOM_STATE}
- Model estimators: {MODEL_ESTIMATORS}
- Features: {len(features)}
- Sample size: {total:,}

---
Generated by Finomaly Experiment Tracking.
"""

    filename = f"{experiment_name.lower().replace(' ', '_')}.md"

    output_path = EXPERIMENT_DIR / filename

    output_path.write_text(report, encoding="utf-8")

    return output_path